import { NextResponse } from 'next/server';
import crypto from 'crypto';
import { db } from '@/lib/db/database';
import { getAuthSession } from '@/lib/auth/session';
import { generateSecureId } from '@/lib/security/cryptoUtils';

export async function POST(request: Request) {
  try {
    const session = await getAuthSession();
    if (!session) {
      return NextResponse.json({ error: 'Unauthorized: Authentication required.' }, { status: 401 });
    }

    const body = await request.json();
    const {
      bookingId,
      razorpay_order_id,
      razorpay_payment_id,
      razorpay_signature,
    } = body;

    if (!bookingId) {
      return NextResponse.json({ error: 'bookingId is required' }, { status: 400 });
    }

    const booking = db.getBookingById(bookingId);
    if (!booking) {
      return NextResponse.json({ error: 'Booking not found' }, { status: 404 });
    }

    // Authorization: Only the booking's customer or an admin can verify payment
    const isCustomer = session.userId === booking.customerId;
    const isAdmin = session.role === 'ADMIN';
    if (!isCustomer && !isAdmin) {
      return NextResponse.json(
        { error: 'Forbidden: You are not authorized to verify payment for this booking.' },
        { status: 403 }
      );
    }

    // Idempotency: If booking is already marked PAID, return existing confirmation safely
    if (booking.status === 'PAID' && booking.payment?.status === 'SUCCESS') {
      return NextResponse.json({
        success: true,
        message: 'Payment already confirmed for this booking.',
        booking,
      });
    }

    const isProduction = process.env.NODE_ENV === 'production';
    const razorpaySecret = process.env.RAZORPAY_KEY_SECRET;
    const razorpayKeyId = process.env.RAZORPAY_KEY_ID;

    // 1. Mandatory server order persistence & integrity check
    if (!razorpay_order_id) {
      return NextResponse.json(
        { error: 'Missing mandatory razorpay_order_id parameter.' },
        { status: 400 }
      );
    }

    const persistedOrder = db.getPaymentByOrderId(razorpay_order_id);
    if (!persistedOrder) {
      return NextResponse.json(
        { error: 'Security Violation: Payment order record was not generated by this server.' },
        { status: 400 }
      );
    }

    if (persistedOrder.bookingId !== booking.id) {
      return NextResponse.json(
        { error: 'Security Violation: This payment order was generated for a different booking.' },
        { status: 400 }
      );
    }

    const expectedAmount = booking.pricing.finalAmount || booking.pricing.estimatedAmount;
    if (persistedOrder.amount !== expectedAmount || persistedOrder.currency !== 'INR') {
      return NextResponse.json(
        { error: 'Security Violation: Payment order amount or currency does not match authorized booking invoice.' },
        { status: 400 }
      );
    }

    // 2. Cryptographic signature and Official Razorpay Gateway API verification
    if (isProduction || razorpaySecret) {
      if (!razorpaySecret) {
        console.error('CRITICAL: RAZORPAY_KEY_SECRET is not configured in production.');
        return NextResponse.json(
          { error: 'Payment gateway configuration error. Please contact support.' },
          { status: 500 }
        );
      }

      if (!razorpay_payment_id || !razorpay_signature) {
        return NextResponse.json(
          { error: 'Missing mandatory payment verification parameters (payment_id, signature).' },
          { status: 400 }
        );
      }

      // Compute HMAC-SHA256 signature
      const generatedSignature = crypto
        .createHmac('sha256', razorpaySecret)
        .update(`${razorpay_order_id}|${razorpay_payment_id}`)
        .digest('hex');

      const genBuf = Buffer.from(generatedSignature);
      const sigBuf = Buffer.from(razorpay_signature);

      const isSignatureValid =
        genBuf.length === sigBuf.length && crypto.timingSafeEqual(genBuf, sigBuf);

      if (!isSignatureValid) {
        return NextResponse.json(
          { error: 'Invalid Razorpay payment signature. Tampering suspected.' },
          { status: 400 }
        );
      }

      // 3. Official Razorpay API verification where live credentials exist
      if (razorpayKeyId && !razorpay_payment_id.startsWith('pay_sim_')) {
        try {
          const authHeader = Buffer.from(`${razorpayKeyId}:${razorpaySecret}`).toString('base64');
          const rzpRes = await fetch(`https://api.razorpay.com/v1/payments/${razorpay_payment_id}`, {
            headers: {
              Authorization: `Basic ${authHeader}`,
              'Content-Type': 'application/json',
            },
          });

          if (rzpRes.ok) {
            const payData = await rzpRes.json();
            if (payData.order_id && payData.order_id !== razorpay_order_id) {
              return NextResponse.json(
                { error: 'Razorpay payment record order_id does not match the active session order.' },
                { status: 400 }
              );
            }
            if (payData.status !== 'captured' && payData.status !== 'authorized') {
              return NextResponse.json(
                { error: `Payment is not confirmed. Gateway status: ${payData.status}.` },
                { status: 400 }
              );
            }
            const expectedPaise = Math.round(expectedAmount * 100);
            if (payData.amount !== expectedPaise) {
              return NextResponse.json(
                { error: 'Payment amount mismatch between gateway and booking invoice.' },
                { status: 400 }
              );
            }
          } else if (isProduction) {
            console.error('Razorpay REST API check returned status:', rzpRes.status);
            return NextResponse.json(
              { error: 'Unable to verify payment with payment gateway.' },
              { status: 502 }
            );
          }
        } catch (fetchErr) {
          console.error('Error contacting Razorpay API:', fetchErr);
          if (isProduction) {
            return NextResponse.json(
              { error: 'Payment gateway communication failure.' },
              { status: 502 }
            );
          }
        }
      }
    } else if (isProduction) {
      // In production, payment verification without signature is strictly impossible
      return NextResponse.json(
        { error: 'Payment signature required in production.' },
        { status: 400 }
      );
    }

    // Update persisted payment record in database
    db.updatePaymentStatus(razorpay_order_id, 'SUCCESS', razorpay_payment_id, razorpay_signature);

    // Amount calculation from server authoritative pricing
    const amountPaid = booking.pricing.finalAmount || booking.pricing.estimatedAmount;

    // Record verified payment
    booking.status = 'PAID';
    booking.updatedAt = new Date().toISOString();
    booking.payment = {
      paymentId: `pay-${Date.now()}`,
      method: 'RAZORPAY',
      status: 'SUCCESS',
      transactionRef: razorpay_payment_id || `RZP_${Date.now()}`,
      paidAt: new Date().toISOString(),
    };

    booking.statusHistory.push({
      status: 'PAID',
      timestamp: new Date().toISOString(),
      note: `Payment of ₹${amountPaid} verified successfully via Razorpay (Txn ID: ${razorpay_payment_id || 'VERIFIED'})`,
      updatedByRole: session.role,
    });

    db.saveBooking(booking);

    // Audit log
    db.addAuditLog({
      id: generateSecureId('aud'),
      actorId: session.userId,
      actorRole: session.role,
      action: 'PAYMENT_VERIFIED_RAZORPAY',
      targetEntity: 'BOOKING',
      targetId: booking.id,
      details: {
        amount: amountPaid,
        orderId: razorpay_order_id || null,
        paymentId: razorpay_payment_id || null,
      },
      timestamp: new Date().toISOString(),
    });

    return NextResponse.json({
      success: true,
      message: 'Razorpay payment verified and confirmed',
      booking,
    });
  } catch (error) {
    console.error('Error in /api/payments/razorpay/verify:', error);
    return NextResponse.json({ error: 'Failed to verify payment' }, { status: 500 });
  }
}
